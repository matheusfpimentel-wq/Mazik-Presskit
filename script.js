function applyLang(lang) {
  const dict = COPY[lang] || COPY.pt;
  document.querySelectorAll("[data-i18n]").forEach((el) => {
    const key = el.getAttribute("data-i18n");
    if (dict[key] !== undefined) el.textContent = dict[key];
  });
  document.querySelectorAll(".lang-btn").forEach((btn) => {
    btn.classList.toggle("active", btn.dataset.lang === lang);
  });
  document.documentElement.setAttribute("lang", lang === "pt" ? "pt-BR" : lang);
  try {
    localStorage.setItem("mzk-lang", lang);
  } catch (e) {}
}

function initialLang() {
  try {
    const saved = localStorage.getItem("mzk-lang");
    if (saved && COPY[saved]) return saved;
  } catch (e) {}
  return "pt";
}

document.querySelectorAll(".lang-btn").forEach((btn) => {
  btn.addEventListener("click", () => applyLang(btn.dataset.lang));
});

applyLang(initialLang());

window.addEventListener("mousemove", (e) => {
  document.querySelectorAll("[data-parallax]").forEach((el) => {
    const k = parseFloat(el.getAttribute("data-parallax")) || 0;
    const dx = (e.clientX / window.innerWidth - 0.5) * k;
    const dy = (e.clientY / window.innerHeight - 0.5) * k;
    el.style.transform = "translate(" + dx.toFixed(1) + "px," + dy.toFixed(1) + "px)";
  });
});
